#!/usr/bin/env python3
"""Copy every published WLED release's firmware into backup/ so this installer
keeps working even if GitHub releases of wled/WLED or download.wled.me go away.

Writes:
  backup/firmware/<tag>/<asset>   - the release files themselves
  backup/releases.json            - saved copy of the GitHub releases list
  backup/index.js                 - which files are backed up (read by app.js)
Nightly builds are skipped (they change every day). Already-saved files are
never downloaded again, and files are never deleted.
"""
import json, os, sys, urllib.request

API = "https://api.github.com/repos/wled/WLED/releases?per_page=100"
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "backup")
FW = os.path.join(ROOT, "firmware")

def get(url, binary=False):
    req = urllib.request.Request(url, headers={"User-Agent": "wled-installer-backup"})
    tok = os.environ.get("GITHUB_TOKEN")
    if tok and "api.github.com" in url:
        req.add_header("Authorization", "Bearer " + tok)
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read() if binary else json.loads(r.read())

releases = [r for r in get(API) if r["tag_name"] != "nightly" and not r.get("draft")]
os.makedirs(FW, exist_ok=True)
added = 0
for rel in releases:
    tag = rel["tag_name"]
    for a in rel["assets"]:
        dest = os.path.join(FW, tag, a["name"])
        if os.path.exists(dest) and os.path.getsize(dest) == a["size"]:
            continue
        if a["size"] > 95_000_000:
            print("skip (too big for git):", tag, a["name"]); continue
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        data = get(a["browser_download_url"], binary=True)
        if len(data) != a["size"]:
            sys.exit(f"size mismatch for {tag}/{a['name']}")
        open(dest, "wb").write(data); added += 1
        print("saved", tag, a["name"], len(data))

# Saved release list (only keep releases we hold firmware for, minus long notes).
saved = []
index = {}
for rel in releases:
    d = os.path.join(FW, rel["tag_name"])
    if not os.path.isdir(d):
        continue
    files = sorted(os.listdir(d))
    index[rel["tag_name"]] = files
    saved.append(rel)
json.dump(saved, open(os.path.join(ROOT, "releases.json"), "w"))
with open(os.path.join(ROOT, "index.js"), "w") as f:
    f.write("// Auto-generated by tools/backup_firmware.py - firmware files held in backup/firmware/\n")
    f.write("window.WLED_BACKUP = " + json.dumps(index, indent=1) + ";\n")
print(f"done: {added} new files, {len(index)} releases backed up")
